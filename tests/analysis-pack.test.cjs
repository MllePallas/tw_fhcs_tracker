test('September pack supplies rolling ranks, cumulative-based quarters, peer cohorts and market comparisons',()=>{
  const p=P.build(history,rules,'2026/09');
  assert.equal(p.coverage.available,13);
  const holding=p.group_stats.holding;
  assert.equal(holding.mom_cohort_count,13);
  assert.deepEqual(holding.excluded_mom,[]);
  assert.equal(holding.increase_count,2);
  assert.equal(holding.decrease_count,11);
  assert.ok(Math.abs(holding.mom.delta-(-331.42))<1e-8);
  assert.ok(Math.abs(holding.mom.pct-(-38.48529889915928))<1e-8);
  assert.equal(holding.yoy_cohort_count,13);
  const fubon=p.holdings.find(r=>r.code==='2881');
  assert.deepEqual([fubon.rank12.rank,fubon.rank12.of],[9,12]);
  assert.ok(Math.abs(fubon.quarter.current-298.8)<1e-8);
  assert.ok(Math.abs(fubon.quarter.previous-640.7)<1e-8);
  assert.ok(Math.abs(fubon.quarter.year_ago-395.8)<1e-8);
  assert.ok(Math.abs(fubon.quarter.qoq.pct-(-53.3635086624))<1e-7);
  const life=p.group_stats.life;
  assert.equal(life.mom_cohort_count,8);
  assert.deepEqual(life.excluded_mom,['三商人壽']);
  assert.equal(life.increase_count,1);assert.equal(life.decrease_count,7);
  assert.ok(Math.abs(life.mom.delta-(-254.74))<1e-8);
  assert.equal(p.group_stats.bank.top_changes[0].name,'台北富邦銀行');
  assert.equal(p.group_stats.bank.top_changes[1].name,'華南銀行');
  assert.equal(p.group_stats.bank.opposite_direction.some(r=>r.name==='凱基銀行'),true);
  assert.equal(p.subsidiaries.find(r=>r.name==='凱基銀行').mom.status,'loss_to_profit');
  assert.equal(p.subsidiaries.find(r=>r.name==='凱基銀行').mom.pct,null);
  assert.equal(p.market_ranks.us10y.rise_rank,1);
  assert.equal(p.market_ranks.tlt.fall_rank,1);
  assert.equal(p.quarter_groups.life.cohort_count,7);
  assert.ok(Math.abs(p.quarter_groups.life.current-339)<1e-8);
  assert.equal(p.quarter_groups.bank.cohort_count,12);
  assert.equal(p.quarter_groups.securities.cohort_count,11);
  assert.equal(p.group_stats.securities.excluded_yoy.includes('永豐金證券'),false);
  assert.equal(p.subsidiaries.find(r=>r.name==='新光人壽').fvoci,null);
  assert.ok(Math.abs(p.holdings.find(r=>r.code==='2883').fvoci.cumulative-936.26)<1e-8);
  assert.deepEqual(p.market_history.map(r=>[r.industry,r.market_key,r.same,r.of]),[
    ['life','tlt',11,15],['life','taiex',11,15],['securities','taiex_turnover',8,15],['securities','taiex',10,15]]);
  assert.ok(p.market_history.every(r=>r.periods.every(period=>period<=p.period)));
});
